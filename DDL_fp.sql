------------------ DDL FINANZAS PERSONALES -------------

-- ---------------------- DIMENSIONES ----------------------

CREATE TABLE dim_categoria (
    ca_id_categorias      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ca_nombre_categorias  VARCHAR2(50) NOT NULL,
    CONSTRAINT pk_dim_categoria PRIMARY KEY (ca_id_categorias),
    CONSTRAINT uq_ca_nombre_categorias UNIQUE (ca_nombre_categorias)
);

CREATE TABLE dim_medio_pago (
    mp_id_medio_pago      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    mp_nombre_medio_pago  VARCHAR2(30) NOT NULL,
    CONSTRAINT pk_dim_medio_pago PRIMARY KEY (mp_id_medio_pago),
    CONSTRAINT uq_mp_nombre_medio_pago UNIQUE (mp_nombre_medio_pago)
);

CREATE TABLE dim_fecha_compra (
    fc_id_fecha_compra  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    fecha               DATE NOT NULL,
    mes                 NUMBER(2) NOT NULL,
    anio                NUMBER(4) NOT NULL,
    CONSTRAINT pk_dim_fecha_compra PRIMARY KEY (fc_id_fecha_compra),
    CONSTRAINT uq_fecha_compra UNIQUE (fecha),
    CONSTRAINT ck_mes_fecha_compra CHECK (mes BETWEEN 1 AND 12),
    CONSTRAINT ck_anio_fecha_compra CHECK (anio >= 2000)
);

-- ---------------------- TABLA DE HECHOS ----------------------
-- Granularidad: un gasto (compra) realizado por el usuario.

CREATE TABLE hecho_gasto (
    hg_id_gasto         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ca_id_categorias    NUMBER NOT NULL,
    mp_id_medio_pago    NUMBER NOT NULL,
    fc_id_fecha_compra  NUMBER NOT NULL,
    descripcion         VARCHAR2(100),
    valor               NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_hecho_gasto PRIMARY KEY (hg_id_gasto),
    CONSTRAINT ck_valor_hecho_gasto CHECK (valor > 0),
    CONSTRAINT fk_gasto_categoria FOREIGN KEY (ca_id_categorias)
        REFERENCES dim_categoria(ca_id_categorias),
    CONSTRAINT fk_gasto_medio_pago FOREIGN KEY (mp_id_medio_pago)
        REFERENCES dim_medio_pago(mp_id_medio_pago),
    CONSTRAINT fk_gasto_fecha FOREIGN KEY (fc_id_fecha_compra)
        REFERENCES dim_fecha_compra(fc_id_fecha_compra)
);